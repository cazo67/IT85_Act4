import ExcelJS from "exceljs";
import pdfMake from "pdfmake";
import helvetica from "pdfmake/standard-fonts/Helvetica.js";

import type { ReportCell, ReportColumnType, ReportDocument } from "./report-model.js";

const { Workbook } = ExcelJS;

pdfMake.addFonts(helvetica as Parameters<typeof pdfMake.addFonts>[0]);
pdfMake.setUrlAccessPolicy(() => false);
const standardFonts = new Set(["Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique"]);
pdfMake.setLocalAccessPolicy((path) => standardFonts.has(path));

export async function renderReportPdf(report: ReportDocument): Promise<Buffer> {
  const parameterText = Object.entries(report.parameters).map(([key, value]) => `${label(key)}: ${value}`).join("   •   ");
  const body = [
    report.columns.map((column) => ({ text: column.label, bold: true, color: "#ffffff", fillColor: "#17324d", margin: [3, 4, 3, 4] })),
    ...report.rows.map((row) => report.columns.map((column) => ({ text: display(row[column.key] ?? "", column.type), alignment: column.type === "money" || column.type === "integer" ? "right" : "left", margin: [3, 3, 3, 3] })))
  ];
  const summary = report.summary.map((item) => `${item.label}: ${display(item.value, item.type)}`).join("   •   ");
  const definition = {
    info: { title: report.title, author: "BCIS" },
    pageOrientation: report.columns.length > 6 ? "landscape" : "portrait",
    pageMargins: [28, 38, 28, 38],
    defaultStyle: { font: "Helvetica", fontSize: 8 },
    footer: (currentPage: number, pageCount: number) => ({ text: `BCIS • Page ${currentPage} of ${pageCount}`, alignment: "center", fontSize: 7, color: "#64748b" }),
    content: [
      { text: "BCIS", fontSize: 10, bold: true, color: "#0f766e" },
      { text: report.title, fontSize: 17, bold: true, margin: [0, 3, 0, 5] },
      { text: parameterText, color: "#475569", margin: [0, 0, 0, 3] },
      { text: `Generated ${report.generatedAt} by ${report.generatedBy}`, color: "#64748b", margin: [0, 0, 0, 12] },
      { table: { headerRows: 1, widths: report.columns.map(() => "*"), body }, layout: "lightHorizontalLines" },
      { text: summary, bold: true, margin: [0, 12, 0, 0] }
    ]
  } as unknown as Parameters<typeof pdfMake.createPdf>[0];
  return pdfMake.createPdf(definition).getBuffer();
}

export async function renderReportXlsx(report: ReportDocument): Promise<Buffer> {
  const workbook = new Workbook();
  workbook.creator = "BCIS";
  workbook.created = new Date(report.generatedAt);
  const sheet = workbook.addWorksheet("Report", { views: [{ state: "frozen", ySplit: 1 }] });
  sheet.columns = report.columns.map((column) => ({ header: column.label, key: column.key, width: column.width ?? Math.max(12, column.label.length + 3) }));
  const header = sheet.getRow(1);
  header.font = { bold: true, color: { argb: "FFFFFFFF" } };
  header.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF17324D" } };
  for (const source of report.rows) {
    const values: Record<string, string | number | Date> = {};
    for (const column of report.columns) values[column.key] = xlsxValue(source[column.key] ?? "", column.type);
    sheet.addRow(values);
  }
  sheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(1, sheet.rowCount), column: report.columns.length } };
  report.columns.forEach((column, index) => {
    if (column.type === "money") sheet.getColumn(index + 1).numFmt = '₱#,##0.00;[Red]-₱#,##0.00';
    if (column.type === "date") sheet.getColumn(index + 1).numFmt = "yyyy-mm-dd";
  });
  const metadata = workbook.addWorksheet("Parameters");
  metadata.addRows([
    ["Report", report.title], ["Code", report.code], ["Generated at", new Date(report.generatedAt)], ["Generated by", safeText(report.generatedBy)],
    ...Object.entries(report.parameters).map(([key, value]) => [label(key), safeText(value)]),
    [], ["Summary", "Value"], ...report.summary.map((item) => [safeText(item.label), xlsxValue(item.value, item.type)])
  ]);
  metadata.getColumn(1).width = 24;
  metadata.getColumn(2).width = 42;
  const output = await workbook.xlsx.writeBuffer();
  return Buffer.from(output);
}

export function safeText(value: string): string { return /^[=+\-@]/.test(value) ? `'${value}` : value; }

function xlsxValue(value: ReportCell, type: ReportColumnType): string | number | Date {
  if (type === "money") return Number(BigInt(value)) / 100;
  if (type === "integer") return Number(value);
  if (type === "date") return new Date(`${String(value)}T00:00:00.000Z`);
  return safeText(String(value));
}
function display(value: ReportCell, type: ReportColumnType): string {
  if (type === "money") { const amount = BigInt(value); const sign = amount < 0n ? "-" : ""; const absolute = amount < 0n ? -amount : amount; return `${sign}PHP ${(absolute / 100n).toLocaleString("en-PH")}.${(absolute % 100n).toString().padStart(2, "0")}`; }
  return String(value);
}
function label(value: string): string { return value.replace(/([A-Z])/g, " $1").replace(/^./, (letter) => letter.toUpperCase()); }
